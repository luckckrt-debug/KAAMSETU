// Generates minimal valid PNG files for Expo app assets

const fs = require('fs');
const path = require('path');

// A valid 1x1 transparent PNG buffer
const minimalPng = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // PNG Signature
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, // IHDR header
  0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x00, 0x64, // 100x100
  0x08, 0x06, 0x00, 0x00, 0x00, 0x70, 0xe1, 0xf5, 0x38, // 8-bit RGBA
  0x00, 0x00, 0x00, 0x1b, 0x49, 0x44, 0x41, 0x54, // IDAT chunk
  0x78, 0x9c, 0x63, 0x60, 0x60, 0x60, 0x00, 0x00, 0x00, 0x04, 0x00, 0x01,
  0x00, 0x18, 0xdd, 0x8d, 0xb0, 0x12, 0x3a, 0x72, 0x0b, 0x00, 0x00, 0x00,
  0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82 // IEND chunk
]);

const apps = ['worker', 'hiring', 'contractor'];

apps.forEach(app => {
  const assetDir = path.resolve(__dirname, `../apps/${app}/assets`);
  if (!fs.existsSync(assetDir)) {
    fs.mkdirSync(assetDir, { recursive: true });
  }

  ['icon.png', 'splash.png', 'adaptive-icon.png', 'favicon.png'].forEach(file => {
    fs.writeFileSync(path.join(assetDir, file), minimalPng);
  });
  console.log(`[ASSETS] Generated assets for apps/${app}`);
});
